local function heading() return ipc.readUW(0x07CC)*360/65536 end
local function course() return ipc.readUW(0x0C4E) end
local function delta(a,b) return ((b-a+540)%360)-180 end
local savedHeading,savedCourse=heading(),course()
ipc.log(string.format('Before heading %.5f course %.5f',savedHeading,savedCourse))
local ok,err=pcall(function()
    local before=heading()
    ipc.control(65879,1)
    ipc.sleep(350)
    local after=heading()
    ipc.log(string.format('HEADING_BUG_INC: %.5f -> %.5f, delta %.5f',before,after,delta(before,after)))
    assert(math.abs(delta(before,after)-1)<0.03,'Heading increment is not one degree')
    ipc.control(65880,1)
    ipc.sleep(350)
    local back=heading()
    ipc.log(string.format('HEADING_BUG_DEC: %.5f -> %.5f, delta %.5f',after,back,delta(after,back)))
    assert(math.abs(delta(after,back)+1)<0.03,'Heading decrement is not one degree')
    before=course()
    ipc.control(65663,0)
    ipc.sleep(350)
    after=course()
    ipc.log(string.format('VOR1_OBI_INC: %.5f -> %.5f, delta %.5f',before,after,delta(before,after)))
    assert(math.abs(delta(before,after)-1)<0.03,'Course increment is not one degree')
    ipc.control(65662,0)
    ipc.sleep(350)
    back=course()
    ipc.log(string.format('VOR1_OBI_DEC: %.5f -> %.5f, delta %.5f',after,back,delta(after,back)))
    assert(math.abs(delta(after,back)+1)<0.03,'Course decrement is not one degree')
    before=heading()
    for i=1,10 do ipc.control(65879,1);ipc.sleep(15) end
    ipc.sleep(350)
    after=heading()
    ipc.log(string.format('10 rapid heading increments: delta %.5f',delta(before,after)))
    assert(math.abs(delta(before,after)-10)<0.03,'Rapid heading commands jumped or were lost')
    for i=1,10 do ipc.control(65880,1);ipc.sleep(15) end
    ipc.sleep(350)
    before=course()
    for i=1,10 do ipc.control(65663,0);ipc.sleep(15) end
    ipc.sleep(350)
    after=course()
    ipc.log(string.format('10 rapid course increments: delta %.5f',delta(before,after)))
    assert(math.abs(delta(before,after)-10)<0.03,'Rapid course commands jumped or were lost')
    for i=1,10 do ipc.control(65662,0);ipc.sleep(15) end
    ipc.sleep(350)
end)
ipc.execInputEvent('INSTRUMENT_HEADING_BUG',savedHeading)
ipc.control(65716,savedCourse)
ipc.sleep(350)
ipc.log(string.format('Restored heading %.5f course %.5f',heading(),course()))
if not ok then error(err) end
ipc.log('PASS: heading and course each move exactly one degree per command')
